def seed():
    conn = get_connection()
    cur = conn.cursor()
    # Check if exercises already exist
    cur.execute("SELECT COUNT(*) FROM exercises")
    count = cur.fetchone()[0]
    if count > 0:
        print(f"Exercises table already has {count} records, skipping seed.")
        cur.close()
        conn.close()
        return

    for name, muscle_group, exercise_type, cal_per_rep, description in EXERCISES:
        cur.execute(
            "INSERT INTO exercises (name, muscle_group, exercise_type, cal_per_rep, description) VALUES (%s,%s,%s,%s,%s)",
            (name, muscle_group, exercise_type, cal_per_rep, description)
        )
    conn.commit()
    cur.close()
    conn.close()
    print(f"Seeded {len(EXERCISES)} exercises successfully!")


if __name__ == "__main__":
    seed()
